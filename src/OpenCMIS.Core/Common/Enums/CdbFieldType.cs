namespace OpenCMIS.Core
{
    /// <summary>
    ///     Defines the types of CDB fields.
    /// </summary>
    public enum CdbFieldType
    {
        /// <summary>
        ///     Byte field type.
        /// </summary>
        Byte = 0,

        /// <summary>
        ///     Word (16-bit) field type.
        /// </summary>
        Word = 1,

        /// <summary>
        ///     DWord (32-bit) field type.
        /// </summary>
        DWord = 2,

        /// <summary>
        ///     String field type.
        /// </summary>
        String = 3
    }
}